//! Generate or verify the committed header; ordinary builds never rewrite source.
use std::{env, fs, path::PathBuf};

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let config = cbindgen::Config {
        language: cbindgen::Language::C,
        include_guard: Some("ECHO_FFI_H".into()),
        cpp_compat: true,
        usize_is_size_t: true,
        header: Some("/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by cargo run -p ffi-header -- --write. Do not edit.\n * EchoResult/payload are borrowed during callbacks only.\n * Destroy on a host worker, never inside callbacks; it drains all callbacks.\n */".into()),
        ..Default::default()
    };
    let bindings = cbindgen::Builder::new()
        .with_crate(root.join("crates/echo-ffi"))
        .with_config(config)
        .generate()
        .expect("generate C ABI");
    let mut bytes = Vec::new();
    bindings.write(&mut bytes);
    let path = root.join("include/echo_ffi.h");
    match env::args().nth(1).as_deref() {
        Some("--write") => {
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, bytes).unwrap();
        }
        Some("--check") => assert_eq!(
            fs::read(path).expect("generate header first"),
            bytes,
            "C header differs from Rust ABI"
        ),
        _ => panic!("Usage: cargo run -p ffi-header -- --write|--check"),
    }
}
